type Metric =
  'revenue' | 'ebit' | 'netIncome' | 'operatingCashFlow' | 'longTermDebt';
type Scope = 'consolidated' | 'standalone';
type VerifiedMetric = {
  metric: Metric;
  state: 'verified';
  amount: string;
  unit: string;
  period: string;
  page: number;
  scope: Scope;
};
export type ReportMetric =
  | VerifiedMetric
  | {
      metric: Metric;
      state: 'missing' | 'needs_review';
    };
type Candidate =
  | VerifiedMetric
  | {
      metric: Metric;
      state: 'needs_review';
      scope: Scope;
    };

type PdfItem = { str: string; transform: number[]; width: number };
type Cell = { text: string; x: number; right: number };
type Row = { y: number; cells: Cell[] };
type YearColumn = { x: number; year: string; date: string; edge?: string };

const METRICS: Record<Metric, RegExp> = {
  revenue:
    /^(?:(?:total )?(?:net sales|(?:net )?revenues?)|przychody (?:netto )?(?:ze sprzedaży|z umów z klientami))$/iu,
  ebit: /^(?:ebit|operating (?:income(?: \(loss\))?|loss|profit)|income from operations|(?:zysk(?: netto| \(strata\))?|strata|wynik) (?:(?:z|na) działalności operacyjnej|operacyjny)(?: \(ebit\))?)$/iu,
  netIncome:
    /^(?:net (?:income(?: \(loss\))?|loss|profit|earnings)|zysk za rok obrotowy|(?:zysk(?: \(strata\))?|strata|wynik) netto(?: \(z uwzględnieniem udziałowców niesprawujących kontroli\))?)$/iu,
  operatingCashFlow:
    /^(?:(?:net )?cash (?:provided by(?: \(used in\))?|generated by|used in|from) operating activities|cash provided by operations|(?:przepływy (?:pieniężne|środków pieniężnych)(?: netto)?|środki pieniężne netto) z działalności operacyjnej(?: netto)?)$/iu,
  longTermDebt:
    /^(?:long-term (?:debt(?: and other borrowings)?|borrowings)(?:, net(?: of current portion)?)?|zadłużenie długoterminowe|długoterminowe kredyty i pożyczki|kredyty i pożyczki długoterminowe)$/iu,
};
const STATEMENTS: { title: RegExp; metrics: Metric[] }[] = [
  {
    title:
      /^(?:statements? of (?:operations|income|profit or loss)|income statements?|rachunek zysków i strat|sprawozdanie z (?:wyniku|całkowitych dochodów))$/iu,
    metrics: ['revenue', 'ebit', 'netIncome'],
  },
  {
    title:
      /^(?:statements? of cash flows|cash flow statements?|rachunek przepływów pieniężnych|sprawozdanie z przepływów pieniężnych)$/iu,
    metrics: ['operatingCashFlow'],
  },
  {
    title:
      /^(?:balance sheets?|statements? of financial position|bilans|sprawozdanie z sytuacji finansowej)$/iu,
    metrics: ['longTermDebt'],
  },
];
const SCOPE_PREFIX =
  /^(consolidated|skonsolidowan\s*[ye]|separate|standalone|jednostkow[ey]) /iu;
const REPORT_SCOPE =
  /^(?:\d+ )?(skonsolidowane|jednostkowe) sprawozdanie finansowe(?: |$)/iu;
const YEAR_CELL =
  /^(?:(od|do) )?(?:(\d{2}\.\d{2}\.)?((?:19|20)\d{2}))\*?(\s*[–-])?$/iu;
const ENGLISH_DATE_CELL =
  /^(?:January|February|March|April|May|June|July|August|September|October|November|December) \d{1,2}, ((?:19|20)\d{2})$/iu;
const ENGLISH_MONTH_DAY =
  /^(?:January|February|March|April|May|June|July|August|September|October|November|December) \d{1,2},$/iu;
const ENGLISH_SCALE =
  /\b(?:in|dollars in) (millions|thousands)\b|\((millions|thousands)\b/iu;
const POLISH_SCALE = /\b(?:w )?(mln|milionach|tys\.?|tysiącach)\b/iu;

function reportScope(prefix: string): Scope {
  return /^(?:consolidated|skonsolidowan)/iu.test(prefix)
    ? 'consolidated'
    : 'standalone';
}

function cellsByRow(items: PdfItem[]): Row[] {
  const rows: Row[] = [];
  for (const item of items.sort((a, b) => b.transform[5]! - a.transform[5]!)) {
    const text = item.str.normalize('NFKC').replace(/\s+/g, ' ').trim();
    if (!text) continue;
    const x = item.transform[4]!;
    const y = item.transform[5]!;
    const cell = { text, x, right: x + item.width };
    const row = rows.at(-1);
    if (row && Math.abs(row.y - y) <= 2) row.cells.push(cell);
    else rows.push({ y, cells: [cell] });
  }
  // Some PDF producers split one word or number into adjacent text items.
  for (const row of rows) {
    const cells: Cell[] = [];
    for (const cell of row.cells.sort((a, b) => a.x - b.x)) {
      const before = cells.at(-1);
      if (
        before &&
        Math.abs(cell.x - before.right) <= 1 &&
        !/[.,:]$/.test(before.text)
      ) {
        before.text += cell.text;
        before.right = cell.right;
      } else {
        cells.push(cell);
      }
    }
    row.cells = cells;
  }
  return rows;
}

function rowText(row: Row) {
  return row.cells.map(({ text }) => text).join(' ');
}

function getYearColumns(row: Row) {
  const cells = row.cells.filter(
    ({ text }) =>
      !/^(?:nota|notes?)$/iu.test(text) &&
      !ENGLISH_SCALE.test(text) &&
      !METRICS.operatingCashFlow.test(text) &&
      !STATEMENTS.some(({ title }) => title.test(text)),
  );
  const columns = cells.flatMap<YearColumn>(({ text, x }) => {
    const date = YEAR_CELL.exec(text);
    if (date) {
      return [
        {
          x,
          year: date[3]!,
          date: (date[2] ?? '') + date[3],
          edge: date[1]?.toLowerCase() ?? (date[4] ? 'od' : undefined),
        },
      ];
    }
    const english = ENGLISH_DATE_CELL.exec(text);
    return english
      ? [{ x, year: english[1]!, date: text, edge: undefined }]
      : [];
  });
  return columns.length >= 2 &&
    columns.length === cells.length &&
    new Set(columns.map(({ year }) => year)).size === columns.length
    ? columns
    : [];
}

function readUnit(headers: string, rows: Row[]) {
  const polishScale = POLISH_SCALE.exec(headers)?.[1];
  const englishScale = ENGLISH_SCALE.exec(headers);
  const scale = polishScale ?? englishScale?.[1] ?? englishScale?.[2];
  if (!scale) return null;
  const currencies = new Set(
    headers.toUpperCase().match(/\b(?:PLN|USD|EUR)\b/g),
  );
  if (currencies.size > 1) return null;
  const currency =
    [...currencies][0] ??
    (/\bzł(?:\s?otych)?(?:\s|[),.]|$)/iu.test(headers) ? 'PLN' : null) ??
    (rows.some((row) =>
      row.cells.some(({ text }) => /^\$(?:\s|\d|$)/.test(text)),
    )
      ? '$'
      : null);
  if (!currency) return null;
  const magnitude = /^(?:mln|milionach|millions)$/i.test(scale)
    ? 'mln'
    : 'tys.';
  return { label: magnitude + ' ' + currency, polish: !!polishScale };
}

function readAmount(raw: string, polish: boolean): string | null {
  const token = raw.replace(/[$€]/g, '').replaceAll('−', '-').trim();
  const parenthesized = /^\(\s*.+\s*\)$/.test(token);
  const value = parenthesized ? token.slice(1, -1).trim() : token;
  const pattern = polish
    ? /^-?(?:\d+|\d{1,3}(?: \d{3})+)(?:,\d+)?$/
    : /^-?(?:\d+|\d{1,3}(?:,\d{3})+)(?:\.\d+)?$/;
  if (!pattern.test(value) || (parenthesized && value.startsWith('-')))
    return null;
  const normalized = (
    polish
      ? value.replaceAll(' ', '').replace(',', '.')
      : value.replaceAll(',', '')
  )
    .replace(/(\.\d*?[1-9])0+$/, '$1')
    .replace(/\.0+$/, '');
  return parenthesized && normalized !== '0' ? '-' + normalized : normalized;
}

function readAlignedAmounts(
  cells: Cell[],
  boundaries: number[],
  polish: boolean,
) {
  const end = boundaries.at(-1)!;
  if (cells.some(({ x, text }) => x >= end && /\d/.test(text))) return null;
  const amounts = boundaries.slice(0, -1).map((start, index) =>
    cells
      .filter(({ x }) => x >= start && x < boundaries[index + 1]!)
      .map(({ text }) => text)
      .join(' '),
  );
  const parsed = amounts.map((raw) => readAmount(raw, polish));
  return parsed.some(
    (value, index) => value === null && !/^[–—-]$/.test(amounts[index]!.trim()),
  )
    ? null
    : parsed;
}

function identifyStatement(headings: string[], footers: string[]) {
  const documentScope = [...headings, ...footers]
    .map((line) => REPORT_SCOPE.exec(line)?.[1])
    .find((value) => value !== undefined);
  for (const [index, line] of headings.entries()) {
    for (const [offset, title] of [
      line,
      line + ' ' + headings[index + 1],
    ].entries()) {
      const prefix = SCOPE_PREFIX.exec(title);
      const definition = STATEMENTS.find(({ title: pattern }) =>
        pattern.test(title.slice(prefix?.[0].length ?? 0)),
      );
      if (!definition) continue;
      // An unqualified table inside a group report can describe a subsidiary.
      const explicitScope =
        prefix?.[1] ??
        (documentScope && reportScope(documentScope) === 'standalone'
          ? documentScope
          : undefined);
      if (explicitScope) {
        return {
          definition,
          heading: index,
          headingEnd: index + offset + 1,
          scope: reportScope(explicitScope),
        };
      }
    }
  }
  return null;
}

export function extractReportMetrics(
  items: PdfItem[],
  page: number,
): Candidate[] {
  const rows = cellsByRow(items);
  const headings = rows.slice(0, 12).map(rowText);
  const footers = rows.slice(-6).map(rowText);
  const statement = identifyStatement(headings, footers);
  if (!statement) return [];
  const { definition, heading, headingEnd, scope } = statement;
  // A quarterly appendix may repeat the main statement with a different column layout.
  if (
    rows
      .slice(0, heading)
      .some((row) =>
        /kwartalna informacja finansowa|quarterly financial information/iu.test(
          rowText(row),
        ),
      )
  )
    return [];

  const headerRows = rows.slice(headingEnd, headingEnd + 15);
  const columnRow = headerRows.findIndex((row) => {
    const columns = getYearColumns(row);
    return columns.length && columns.every(({ edge }) => edge !== 'od');
  });
  const columns = columnRow < 0 ? [] : getYearColumns(headerRows[columnRow]!);
  const headerEnd = columnRow < 0 ? headingEnd : headingEnd + columnRow + 1;
  const first = columns[0]?.x ?? Infinity;
  const gap = columns.length >= 2 ? columns[1]!.x - first : 0;
  const numberStart = first - gap / 2;
  const latest = columns.reduce(
    (best, current, index) =>
      current.year > (columns[best]?.year ?? '') ? index : best,
    -1,
  );
  const column = columns[latest];
  const last = columns.at(-1);
  const penultimate = columns.at(-2);
  const numberEnd =
    last && penultimate ? last.x + (last.x - penultimate.x) * 0.85 : Infinity;
  const boundaries = [
    numberStart,
    ...columns
      .slice(1)
      .map((current, index) => (columns[index]!.x + current.x) / 2),
    numberEnd,
  ];
  const headers = rows.slice(0, headerEnd).map(rowText).join('\n');
  const extraUnit = rows
    .slice(headerEnd, headerEnd + 2)
    .map(rowText)
    .filter((line) =>
      /^\((?:in |dollars in |w )?(?:millions|thousands|mln|tys\.)\b/iu.test(
        line,
      ),
    );
  const footerUnits = footers.filter((line) =>
    /^\(wszystkie kwoty podane są w /iu.test(line),
  );
  const unit = readUnit(
    [headers, ...extraUnit, ...footerUnits].join('\n'),
    rows.slice(headerEnd, headerEnd + 35),
  );
  const starts =
    headerRows
      .slice(0, Math.max(0, columnRow))
      .map(getYearColumns)
      .findLast(
        (row) =>
          row.length === columns.length &&
          row.every(({ edge }) => edge === 'od'),
      ) ?? [];
  const start = starts[latest];
  let period: string | undefined;
  if (column && definition.metrics.includes('longTermDebt')) {
    const days = headerRows[columnRow - 1]?.cells.filter(({ text }) =>
      ENGLISH_MONTH_DAY.test(text),
    );
    const day =
      days?.length === columns.length
        ? days[latest]
        : days?.length === 1
          ? days[0]
          : undefined;
    period = day ? day.text + ' ' + column.year : column.date;
  } else if (
    column?.edge !== 'od' &&
    start?.edge === 'od' &&
    column?.year === start.year
  ) {
    period = start.date + ' – ' + column.date;
  } else if (
    !column?.edge &&
    !/quarter|(?:three|six|nine) months ended|kwartał|półrocze/iu.test(headers)
  ) {
    period = column?.year;
  }

  const facts: Candidate[] = [];
  let noncurrentLiabilities = false;
  for (const row of rows.slice(headerEnd)) {
    const label = row.cells
      .filter(
        ({ x, text }) =>
          x < numberStart &&
          /\p{L}/u.test(text) &&
          !/^(?:nota|note)\b/iu.test(text),
      )
      .map(({ text }) => text)
      .join(' ')
      .replace(/[:*]+$/, '')
      .trim();
    if (
      /^(?:non[ -]?current liabilities|zobowiązania długoterminowe)$/iu.test(
        label,
      )
    )
      noncurrentLiabilities = true;
    if (/^(?:current liabilities|zobowiązania krótkoterminowe)$/iu.test(label))
      noncurrentLiabilities = false;
    const metric = definition.metrics.find(
      (key) =>
        METRICS[key].test(label) ||
        (key === 'longTermDebt' &&
          noncurrentLiabilities &&
          /^term debt$/iu.test(label)),
    );
    if (!metric) continue;
    let parsed = unit
      ? readAlignedAmounts(row.cells, boundaries, unit.polish)
      : null;
    // Text can be right-aligned under left-aligned years. Keep any leading numeric cell ambiguous.
    if (
      unit &&
      !parsed &&
      !row.cells.some(
        ({ x, text }) => x >= numberStart && x < first && /\d/.test(text),
      )
    ) {
      parsed = readAlignedAmounts(
        row.cells,
        [...columns.map(({ x }) => x), numberEnd],
        unit.polish,
      );
    }
    const amount = parsed?.[latest];
    facts.push(
      amount && unit && period
        ? {
            metric,
            state: 'verified',
            amount,
            unit: unit.label,
            period,
            page,
            scope,
          }
        : { metric, state: 'needs_review', scope },
    );
  }
  return facts;
}

export function summarizeMetrics(candidates: Candidate[]): ReportMetric[] {
  const scope = candidates.some((item) => item.scope === 'consolidated')
    ? 'consolidated'
    : 'standalone';
  return (Object.keys(METRICS) as Metric[]).map((metric) => {
    const matches = candidates.filter(
      (item) => item.metric === metric && item.scope === scope,
    );
    const verified = matches.filter((item) => item.state === 'verified');
    const first = verified[0];
    if (
      first &&
      verified.every(
        ({ amount, unit, period }) =>
          amount === first.amount &&
          unit === first.unit &&
          period === first.period,
      )
    )
      return first;
    return { metric, state: matches.length ? 'needs_review' : 'missing' };
  });
}
